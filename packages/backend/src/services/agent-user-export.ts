/**
 * STORE-MAP-01 P7 (SEC2-4): an optional user-level copy of a Girru agent for a
 * coding app, generated from the agent's package (P5, services/agent-package.ts).
 *
 *   Claude Code   ~/.claude/agents/girru-<name>.md   (a subagent file)
 *
 * The file goes into the user's own home only, never into a project folder.
 * It carries the agent's name, description, instructions and personality
 * (secrets already hidden by the package, checked again here) and the names of
 * its specialties and skills. Never permissions, memory, notes, knowledge files
 * or keys. Girru's hidden line under the header marks the file as Girru's:
 *
 *   <!-- girru:agent id=<agent id> package=<hash> · ... -->
 *
 * A file without that line (or with another agent's) is the owner's own and is
 * never changed or removed. Write = preview -> apply with the preview's hash,
 * through the one safe file writer (SEC2-6); remove takes only Girru's file.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { exportAgentPackage, packageHashOf, AgentPackageError } from './agent-package.js';
import { redactImportText } from '../memory/import/redact.js';
import { safeWriteFile, SafeFileError, sha256 } from './safe-file.js';
import { readRegularFile } from '../memory/bridge/regular-file.js';

export const USER_EXPORT_TOOLS = ['claude-code'] as const;
export type UserExportTool = typeof USER_EXPORT_TOOLS[number];
const MAX_EXPORT_BYTES = 256 * 1024;
const MAX_TEXT = 60_000;

export class UserExportError extends Error {
  constructor(readonly status: number, readonly code: string, message: string) { super(message); }
}

export interface UserExportPreview {
  agentId: string;
  tool: UserExportTool;
  /** Shown to the owner with `~` for the home folder. */
  file: string;
  action: 'create' | 'update' | 'unchanged' | 'conflict';
  reason: string | null;
  text: string;
  previewHash: string;
}

const MARK = /<!-- girru:agent id=([A-Za-z0-9_-]+) package=[a-f0-9]+ /;

/** `girru-<ascii name>` (lower case, digits, dashes), or `girru-agent-<id>` when nothing is left. */
export function userExportName(agentName: string, agentId: string): string {
  const base = String(agentName ?? '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40).replace(/-+$/g, '');
  return base ? `girru-${base}` : `girru-agent-${agentId.replace(/[^A-Za-z0-9]/g, '').slice(0, 12).toLowerCase()}`;
}

const relativeOf = (name: string) => `.claude/agents/${name}.md`;
const oneLine = (s: unknown, max: number) => { const t = String(s ?? '').replace(/\s+/g, ' ').trim(); return t.length > max ? `${t.slice(0, max - 1)}…` : t; };
const cut = (s: unknown) => { const t = String(s ?? '').trim(); return t.length > MAX_TEXT ? `${t.slice(0, MAX_TEXT - 1)}…` : t; };

/** The subagent file for one agent (pure apart from reading the package). */
export async function userExportText(agentId: string): Promise<{ name: string; text: string }> {
  const pkg = await exportAgentPackage(agentId) as {
    agent: { name: string; description: string; role: string | null; department: string | null };
    instructions: string; personality: { text: string }; specialties: { name: string }[]; skills: { name: string }[];
  };
  // The content's hash without the export time, so the same agent gives the same file.
  const { provenance: _p, packageHash: _h, ...content } = pkg as unknown as Record<string, unknown>;
  const contentHash = packageHashOf(content);
  const name = userExportName(pkg.agent.name, agentId);
  const description = oneLine(pkg.agent.description || `${pkg.agent.name}, a Girru agent${pkg.agent.role ? ` (${pkg.agent.role})` : ''}`, 300).replace(/^[-\s]+/, '');
  const body: string[] = [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    '---',
    `<!-- girru:agent id=${agentId} package=${contentHash.slice(0, 16)} · generated by Girru from this agent's package; Girru replaces or removes this file only while this line is here. Permissions, memory and keys are never copied. -->`,
    '',
    `You are ${oneLine(pkg.agent.name, 80)}, an agent of the owner's Girru company${pkg.agent.department ? ` in the ${oneLine(pkg.agent.department, 60)} department` : ''}.`,
    'Read the project memory through the Girru MCP tools (`project_brief`, `latest_handoff`) before you start, and leave `handoff_write` notes when you stop.',
  ];
  if (cut(pkg.personality.text)) body.push('', '## Personality', '', cut(pkg.personality.text));
  if (cut(pkg.instructions)) body.push('', '## Instructions from the owner', '', cut(pkg.instructions));
  const specs = pkg.specialties.map((s) => oneLine(s.name, 80)).filter(Boolean);
  const skills = pkg.skills.map((s) => oneLine(s.name, 80)).filter(Boolean);
  if (specs.length || skills.length) {
    body.push('', '## Specialties and skills', '');
    if (specs.length) body.push(`- Specialties: ${specs.join(', ')}`);
    if (skills.length) body.push(`- Skills: ${skills.join(', ')}`);
  }
  const text = `${body.join('\n')}\n`;
  // The package hid secrets already; anything that still looks like one stops the export.
  if (Object.values(redactImportText(text).counts).some((n) => Number(n) > 0)) throw new UserExportError(422, 'secret_found', 'The agent text still contains something that looks like a secret; nothing was written');
  if (Buffer.byteLength(text, 'utf8') > MAX_EXPORT_BYTES) throw new UserExportError(413, 'too_large', 'The agent text is too long for a coding app file');
  return { name, text };
}

function current(home: string, relative: string): { sha: string | null; text: string | null; problem: string | null } {
  const file = path.join(home, relative);
  let st: fs.Stats | null = null;
  try { st = fs.lstatSync(file); } catch (e) { if ((e as NodeJS.ErrnoException).code !== 'ENOENT') return { sha: null, text: null, problem: 'The file cannot be read' }; }
  if (!st) return { sha: null, text: null, problem: null };
  if (st.isSymbolicLink() || !st.isFile()) return { sha: null, text: null, problem: 'The file is a link or not a plain file' };
  try {
    const { bytes } = readRegularFile(file, MAX_EXPORT_BYTES);
    return { sha: sha256(bytes), text: bytes.toString('utf8'), problem: null };
  } catch { return { sha: null, text: null, problem: 'The file is too large or changed while it was read' }; }
}

function tool(t: unknown): UserExportTool {
  if (t === undefined || t === null || t === '') return 'claude-code';
  if (!(USER_EXPORT_TOOLS as readonly string[]).includes(String(t))) throw new UserExportError(400, 'unknown_tool', 'Unknown coding app');
  return t as UserExportTool;
}

function wrap<T>(fn: () => Promise<T>): Promise<T> {
  return fn().catch((err) => {
    if (err instanceof AgentPackageError) throw new UserExportError(err.status, err.code, err.message || err.code);
    if (err instanceof SafeFileError) throw new UserExportError(409, 'unsafe_path', err.message);
    throw err;
  });
}

/** What writing the agent's user-level file would do. Writes nothing. */
export function userExportPreview(agentId: string, toolInput?: unknown, home = os.homedir()): Promise<UserExportPreview> {
  return wrap(async () => {
    const t = tool(toolInput);
    const { name, text } = await userExportText(agentId);
    const relative = relativeOf(name);
    const cur = current(home, relative);
    const owner = cur.text ? MARK.exec(cur.text)?.[1] ?? null : null;
    let action: UserExportPreview['action'];
    let reason: string | null = null;
    if (cur.problem) { action = 'conflict'; reason = cur.problem; }
    else if (cur.text === null) action = 'create';
    else if (owner !== agentId) { action = 'conflict'; reason = owner ? 'The file belongs to another Girru agent' : 'The file is your own, not Girru\'s; Girru leaves it as it is'; }
    else action = cur.sha === sha256(text) ? 'unchanged' : 'update';
    const previewHash = createHash('sha256').update(JSON.stringify([agentId, t, relative, cur.sha, sha256(text)])).digest('hex');
    return { agentId, tool: t, file: `~/${relative}`, action, reason, text, previewHash };
  });
}

/** Write the file the owner saw (the preview's hash), never over a file that is not Girru's. */
export function userExportApply(agentId: string, input: { tool?: unknown; previewHash?: unknown; confirm?: unknown }, home = os.homedir()): Promise<UserExportPreview> {
  return wrap(async () => {
    if (input?.confirm !== true) throw new UserExportError(400, 'confirm_required', 'Send confirm: true after reviewing the preview');
    const p = await userExportPreview(agentId, input.tool, home);
    if (p.previewHash !== input.previewHash) throw new UserExportError(409, 'preview_stale', 'The agent or the file changed since the preview; preview again');
    if (p.action === 'conflict') throw new UserExportError(409, 'conflict', p.reason ?? 'Nothing written');
    if (p.action !== 'unchanged') {
      const relative = p.file.slice(2);
      const cur = current(home, relative);
      safeWriteFile(home, relative, p.text, { expectSha256: cur.sha, maxBytes: MAX_EXPORT_BYTES });
    }
    return userExportPreview(agentId, input.tool, home);
  });
}

/** Remove Girru's file of this agent (OPS8: only Girru's). A file that is not Girru's stays. */
export function userExportRemove(agentId: string, toolInput?: unknown, home = os.homedir()): Promise<{ removed: boolean; file: string }> {
  return wrap(async () => {
    tool(toolInput);
    const { name } = await userExportText(agentId);
    const relative = relativeOf(name);
    const cur = current(home, relative);
    if (cur.problem) throw new UserExportError(409, 'conflict', cur.problem);
    if (cur.text === null) return { removed: false, file: `~/${relative}` };
    if (MARK.exec(cur.text)?.[1] !== agentId) throw new UserExportError(409, 'not_girru', 'The file is not Girru\'s copy of this agent; Girru leaves it as it is');
    fs.rmSync(path.join(home, relative));
    return { removed: true, file: `~/${relative}` };
  });
}
