// ── Spies (installed before any app module loads) ──────────────────────────
const intervals = new Set();
const timeouts = new Map();
const realSetInterval = globalThis.setInterval;
const realClearInterval = globalThis.clearInterval;
const realSetTimeout = globalThis.setTimeout;
const realClearTimeout = globalThis.clearTimeout;
let tracking = true;
globalThis.setInterval = function (fn, ms, ...a) {
  const h = realSetInterval(fn, ms, ...a);
  if (tracking) intervals.add({ h, ms, stack: new Error().stack });
  return h;
};
globalThis.clearInterval = function (h) {
  for (const i of intervals) if (i.h === h) intervals.delete(i);
  return realClearInterval(h);
};
globalThis.setTimeout = function (fn, ms, ...a) {
  let rec;
  const h = realSetTimeout((...x) => { timeouts.delete(h); return fn(...x); }, ms, ...a);
  if (tracking) { rec = { ms, stack: new Error().stack }; timeouts.set(h, rec); }
  return h;
};
globalThis.clearTimeout = function (h) {
  timeouts.delete(h);
  return realClearTimeout(h);
};

