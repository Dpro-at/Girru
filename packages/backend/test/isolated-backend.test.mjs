function filesUnder(dir) {
  const out = [];
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      out.push(p);
      if (e.isDirectory()) walk(p);
    }
  };
  walk(dir);
  return out;
}

test('background off: the boot leaves no interval, pending timer, cron task, watcher or child process', () => {
  assert.equal(summary.background, false);
  assert.equal(summary.dockerAvailable, false);
  assert.deepEqual([...intervals].map((i) => i.stack.split('\n').slice(2, 5).join(' | ')), [], 'no setInterval left active');
  const pending = [...timeouts.values()].map((t) => `${t.ms}ms ${t.stack.split('\n').slice(2, 5).join(' | ')}`);
  assert.deepEqual(pending, [], 'no setTimeout left pending');
  assert.deepEqual(cronCalls, [], 'no node-cron task');
  assert.deepEqual(spawned, [], 'no child process');
  const resources = process.getActiveResourcesInfo();
  for (const kind of ['FSEventWrap', 'StatWatcher', 'Timeout', 'ProcessWrap']) {
    assert.equal(resources.includes(kind), false, `no active ${kind} (${resources.join(',')})`);
  }
  assert.deepEqual(fetched, [], 'no outbound fetch during boot');
  assert.ok(BACKGROUND_JOBS.length >= 20);
});

test('the spies see what the guards block (the switch is what keeps the boot quiet)', async () => {
  const { getCronEngine } = await import(join(backendDir, 'src/scheduler/engine.ts'));
  const engine = getCronEngine();
  const job = { id: 'iso-probe', name: 'iso-probe', cronExpression: '0 3 * * *', actionType: 'memory-job', actionData: {}, enabled: true, createdAt: new Date(), updatedAt: new Date() };
  engine.scheduleJob(job);
  assert.equal(cronCalls.length, 0, 'background off: scheduleJob creates no node-cron task');
  assert.ok(engine.getJob('iso-probe'), 'the job is still known');
  process.env.AGENT_PLAYER_BACKGROUND = 'on';
  try {
    engine.scheduleJob(job);
    assert.equal(cronCalls.length, 1, 'background on: the same call reaches node-cron (the spy works)');
  } finally {
    engine.unscheduleJob('iso-probe');
    process.env.AGENT_PLAYER_BACKGROUND = 'off';
    cronCalls.length = 0;
  }
  tracking = true;
  const probe = setInterval(() => {}, 1000);
  tracking = false;
  assert.equal(intervals.size, 1, 'the interval spy records');
  clearInterval(probe);
  assert.equal(intervals.size, 0);
});

