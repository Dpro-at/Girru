test('BUG-01: database stats and backup use the main database under the data root', async () => {
  const db = getDatabase();
  db.prepare(`INSERT INTO users (id, email, username, password_hash, role, status, email_verified) VALUES ('iso-owner', 'iso-owner@example.test', 'iso-owner', 'x', 'owner', 'active', 1)`).run();
  const auth = { authorization: `Bearer ${generateToken('iso-owner', 1)}` };
  const stats = await app.inject({ method: 'GET', url: '/api/database/stats', headers: auth });
  assert.equal(stats.statusCode, 200, stats.body);
  assert.equal(JSON.parse(stats.body).totalSize, statSync(join(dataDir, 'agent-player.db')).size);
  const backup = await app.inject({ method: 'POST', url: '/api/database/backup', headers: { ...auth, 'content-type': 'application/json', origin: 'http://127.0.0.1:42522' }, payload: '{}' });
  assert.equal(backup.statusCode, 200, backup.body);
  const { filename } = JSON.parse(backup.body).backup;
  assert.ok(existsSync(join(dataDir, 'backups', filename)));
  // Traversal names are refused; an online restore is refused (it would overwrite the open DB).
  const evil = await app.inject({ method: 'GET', url: `/api/database/backups/${encodeURIComponent('../agent-player.db')}`, headers: auth });
  assert.equal(evil.statusCode, 404);
  const restore = await app.inject({ method: 'POST', url: '/api/database/restore', headers: { ...auth, 'content-type': 'application/json', origin: 'http://127.0.0.1:42522' }, payload: JSON.stringify({ filename }) });
  assert.equal(restore.statusCode, 409);
  assert.equal(JSON.parse(restore.body).code, 'restore_offline_only');
});

