// STORE-MAP-01 P3: build the upgrade fixtures from the released schemas.
// For each release tag it applies that release's schema.sql and migrations to a
// throwaway SQLite file (as Database.initialize did then), adds a small synthetic
// company (owner, agents with departments, a chat project, project memory, a
// memory-only project, a rule naming a department nobody uses), and writes the
// result as plain SQL to test/fixtures/upgrade/girru-<tag>.sql.
// Synthetic data only. Run from packages/backend: node scripts/store-p3/make-upgrade-fixtures.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import Database from 'better-sqlite3';

const TAGS = ['v1.3.2', 'v1.4.1'];
const ROOT = 'packages/backend/src/db';
const git = (...a) => execFileSync('git', a, { encoding: 'utf8', maxBuffer: 64 << 20 });

function build(tag) {
  const dir = mkdtempSync(join(tmpdir(), 'girru-fixture-'));
  const db = new Database(join(dir, 'a.db'));
  db.exec(git('show', `${tag}:${ROOT}/schema.sql`));
  db.exec('CREATE TABLE IF NOT EXISTS migrations (id TEXT PRIMARY KEY, name TEXT NOT NULL, applied_at DATETIME DEFAULT CURRENT_TIMESTAMP)');
  const files = git('ls-tree', '--full-tree', '--name-only', tag, `${ROOT}/migrations/`).split('\n').filter((f) => f.endsWith('.sql')).sort();
  for (const f of files) {
    const name = f.split('/').pop().replace('.sql', '');
    db.transaction(() => { db.exec(git('show', `${tag}:${f}`)); db.prepare('INSERT INTO migrations (id, name, applied_at) VALUES (?, ?, ?)').run(name.split('_')[0], name, '2026-10-01 00:00:00'); })();
  }
  seed(db);
  const out = dump(db);
  db.close();
  rmSync(dir, { recursive: true, force: true });
  return out;
}

const has = (db, table, col) => db.prepare(`SELECT 1 FROM pragma_table_info(?) WHERE name = ?`).get(table, col);

function seed(db) {
  const now = '2026-10-01T09:00:00.000Z';
  db.prepare(`INSERT INTO users (id, email, username, password_hash, role, status, email_verified) VALUES ('fx-owner', 'owner@example.test', 'owner', 'x', 'owner', 'active', 1)`).run();
  const agent = db.prepare(`INSERT INTO agents_config (id, name, provider, model, department) VALUES (?, ?, 'ollama', 'qwen-test', ?)`);
  agent.run('fx-a1', 'Omar', 'engineering');
  agent.run('fx-a2', 'Nora', 'Marketing');
  agent.run('fx-a3', 'Lina', 'hr');
  db.prepare(`INSERT INTO chat_projects (id, user_id, name, slug) VALUES ('fx-p1', 'fx-owner', 'Alpha', 'alpha')`).run();
  const mem = db.prepare(`INSERT INTO memories (id, user_id, type, content, created_at, drawer_kind, drawer_key) VALUES (?, 'fx-owner', ?, ?, ?, ?, ?)`);
  mem.run('fx-m1', 'fact', 'Alpha ships on Fridays.', now, 'project', 'alpha');
  mem.run('fx-m2', 'decision', 'Use SQLite for the desktop app.', now, 'project', 'alpha');
  mem.run('fx-m3', 'preference', 'Samir likes short answers.', now, 'owner', '');
  mem.run('fx-m4', 'fact', 'The beta list has 40 people.', now, 'project', 'beta-notes');
  if (db.prepare(`SELECT 1 FROM sqlite_master WHERE name = 'memory_departments'`).get()) {
    db.prepare(`INSERT INTO memory_departments (id, owner_id, name, norm_name) VALUES ('dept-fx1', 'fx-owner', 'Engineering', 'engineering')`).run();
    db.prepare(`INSERT INTO memory_project_scopes (owner_id, slug, name, department_id) VALUES ('fx-owner', 'alpha', 'Alpha', 'dept-fx1')`).run();
  }
  if (db.prepare(`SELECT 1 FROM sqlite_master WHERE name = 'agent_rules'`).get()) {
    db.prepare(`INSERT INTO agent_rules (id, text, who, targets) VALUES ('fx-r1', 'Answer in the owner''s language.', 'departments', '["engineering","designers"]')`).run();
  }
  if (has(db, 'agents_config', 'specialty')) db.prepare(`UPDATE agents_config SET specialty = 'backend' WHERE id = 'fx-a1'`).run();
}

function dump(db) {
  const lines = ['-- Generated by scripts/store-p3/make-upgrade-fixtures.mjs. Synthetic data only.', 'PRAGMA foreign_keys = OFF;', 'BEGIN;'];
  const objs = db.prepare(`SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'view' THEN 2 ELSE 3 END, rowid`).all();
  const tables = objs.filter((o) => o.type === 'table');
  for (const t of tables) lines.push(t.sql + ';');
  for (const t of tables) {
    if (t.sql.includes('VIRTUAL TABLE')) continue;
    if (/_(content|segments|segdir|docsize|stat|config|data|idx)$/.test(t.name) && tables.some((v) => v.sql.includes('VIRTUAL TABLE') && t.name.startsWith(v.name + '_'))) continue;
    for (const r of db.prepare(`SELECT * FROM "${t.name}"`).all()) {
      const cols = Object.keys(r);
      const vals = cols.map((c) => (r[c] === null ? 'NULL' : typeof r[c] === 'number' ? String(r[c]) : Buffer.isBuffer(r[c]) ? `X'${r[c].toString('hex')}'` : `'${String(r[c]).replace(/'/g, "''")}'`));
      lines.push(`INSERT INTO "${t.name}" (${cols.map((c) => `"${c}"`).join(', ')}) VALUES (${vals.join(', ')});`);
    }
  }
  for (const o of objs.filter((x) => x.type !== 'table' && !(x.type === 'index' && /^sqlite_autoindex/.test(x.name)))) lines.push(o.sql + ';');
  lines.push('COMMIT;');
  return lines.join('\n') + '\n';
}

for (const tag of TAGS) {
  const sqlText = build(tag);
  const file = join('test/fixtures/upgrade', `girru-${tag.slice(1)}.sql`);
  writeFileSync(file, sqlText);
  console.log(`${file}: ${(sqlText.length / 1024).toFixed(0)} KB`);
}
